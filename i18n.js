(function () {
  const data = window.DSMA_I18N;
  const KEY = "dsma-lang";
  const supported = data.langs.map((l) => l.code);
  let current = "en";

  window.t = (key, vars) => {
    let text = (data.strings[current] && data.strings[current][key]) ?? data.strings.en[key] ?? key;
    if (vars) for (const [name, value] of Object.entries(vars)) text = text.replace(`{${name}}`, value);
    return text;
  };
  window.currentLang = () => current;

  function pick() {
    try { const saved = localStorage.getItem(KEY); if (supported.includes(saved)) return saved; } catch {}
    for (const tag of navigator.languages || [navigator.language || "en"]) {
      const code = String(tag).toLowerCase().split("-")[0];
      if (supported.includes(code)) return code;
    }
    return "en";
  }

  function apply(code) {
    current = code;
    const meta = data.langs.find((l) => l.code === code);
    document.documentElement.lang = code;
    document.documentElement.dir = meta.dir;
    document.querySelectorAll("[data-i18n]").forEach((node) => { node.textContent = window.t(node.dataset.i18n); });
    document.querySelectorAll("[data-i18n-html]").forEach((node) => { node.innerHTML = window.t(node.dataset.i18nHtml); });
    document.querySelectorAll("[data-i18n-ph]").forEach((node) => { node.placeholder = window.t(node.dataset.i18nPh); });
    document.querySelectorAll("[data-i18n-title]").forEach((node) => { node.title = window.t(node.dataset.i18nTitle); });
    document.querySelectorAll("[data-i18n-label]").forEach((node) => { node.setAttribute("aria-label", window.t(node.dataset.i18nLabel)); });
    document.querySelectorAll(".lang-option").forEach((button) => button.setAttribute("aria-pressed", String(button.dataset.lang === code)));
    const select = document.querySelector(".lang-select"); if (select) select.value = code;
    document.dispatchEvent(new CustomEvent("dsma:lang", { detail: code }));
  }

  window.setLang = (code) => {
    if (!supported.includes(code)) return;
    try { localStorage.setItem(KEY, code); } catch {}
    apply(code);
  };

  function buildBar() {
    const host = document.querySelector(".lang-bar-options");
    if (!host) return;
    host.innerHTML = data.langs.map((l) => `<button class="lang-option" type="button" lang="${l.code}" data-lang="${l.code}" aria-pressed="false">${l.name}</button>`).join("");
    host.addEventListener("click", (event) => { const button = event.target.closest(".lang-option"); if (button) window.setLang(button.dataset.lang); });
    const select = document.querySelector(".lang-select");
    if (select) { select.innerHTML = data.langs.map((l) => `<option value="${l.code}" lang="${l.code}">${l.name}</option>`).join(""); select.addEventListener("change", () => window.setLang(select.value)); }
  }

  buildBar();
  apply(pick());
})();
